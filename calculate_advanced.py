import pandas as pd
import numpy as np

print("Загружаем данные с энтропией...")
df = pd.read_csv('dataset_forge_math.csv')

classes = ['Собака', 'Кошка', 'Мышь']
prob_cols = ['prob_Собака', 'prob_Кошка', 'prob_Мышь']

print("1. Ищем ошибки разметки...")
# Находим индекс максимальной вероятности и определяем, какой класс предсказала модель
predicted_idx = np.argmax(df[prob_cols].values, axis=1)
df['предсказанный_класс'] = [classes[i] for i in predicted_idx]

# Если модель и человек не согласны, степень ошибки = уверенность модели. 
# Если согласны - ошибки нет (0.0).
df['вероятность_ошибки_разметки'] = np.where(
    df['истинный_класс'] != df['предсказанный_класс'],
    1.0 - df['неуверенность'], 
    0.0
)

print("2. Ищем дубликаты...")
# Помечаем строки, где вероятности и классы полностью совпадают с другими строками
df['дубликат'] = df.duplicated(subset=prob_cols + ['истинный_класс'], keep=False)

print("3. Считаем дефицит классов...")
# Считаем, сколько у нас объектов каждого класса
class_counts = df['истинный_класс'].value_counts()
total_objects = len(df)
ideal_share = 1.0 / len(classes) # Идеально: по 33.3% на класс

# Функция для вычисления "веса" дефицита
def calculate_deficit(class_name):
    real_share = class_counts[class_name] / total_objects
    # Чем меньше реальная доля по сравнению с идеальной, тем выше вес (дефицит)
    return round(ideal_share / real_share, 4)

df['дефицит_класса'] = df['истинный_класс'].apply(calculate_deficit)

print("4. Высчитываем Интегральную полезность...")
# Нормализуем энтропию (максимальная для 3 классов примерно 1.585)
norm_entropy = df['энтропия'] / 1.585

# Формула полезности: ценность состоит из неопределенности (40%), 
# вероятности найти ошибку (40%) и ценности редкого класса (20%)
df['полезность'] = np.where(
    df['дубликат'],
    0.0, # Дубликаты нам не нужны, их полезность = 0
    norm_entropy * 0.4 + df['вероятность_ошибки_разметки'] * 0.4 + df['дефицит_класса'] * 0.2
)

# Округляем для красоты
df['вероятность_ошибки_разметки'] = df['вероятность_ошибки_разметки'].round(4)
df['полезность'] = df['полезность'].round(4)

# Сохраняем итоговый, математически заряженный датасет!
df.to_csv('dataset_forge_final.csv', index=False, encoding='utf-8')
print("Готово! Итоговый файл сохранен как 'dataset_forge_final.csv'")
