import pandas as pd
import numpy as np

print("Читаю сырые данные...")
# 1. Загружаем наш сгенерированный датасет
df = pd.read_csv('dataset_forge.csv')

# 2. Выделяем только те колонки, где лежат вероятности
prob_cols = ['prob_Собака', 'prob_Кошка', 'prob_Мышь']
# Превращаем их в матрицу (числовой массив) для быстрых математических операций
probs = df[prob_cols].values 

print("Считаю неуверенность и энтропию...")

# 3. Показатель неуверенности (1 - максимальная вероятность)
# Находим самую большую вероятность для каждой строки (axis=1)
max_probs = np.max(probs, axis=1)
df['неуверенность'] = 1.0 - max_probs

# 4. Энтропия (Сумма: -p * log2(p))
# Добавляем микроскопическое число 1e-9 к вероятностям, 
# чтобы избежать математической ошибки "логарифм от нуля", если вероятность равна 0
entropy = -np.sum(probs * np.log2(probs + 1e-9), axis=1)
df['энтропия'] = entropy

# Округляем значения до 4 знаков после запятой, чтобы таблица выглядела аккуратно
df['неуверенность'] = df['неуверенность'].round(4)
df['энтропия'] = df['энтропия'].round(4)

# 5. Сохраняем новую версию датасета
df.to_csv('dataset_forge_math.csv', index=False, encoding='utf-8')
print("Успех! Сохранен новый файл: 'dataset_forge_math.csv'")
